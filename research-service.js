// generateChronicle — «Летопись»: длинный связный рассказ о роде от
// самых дальних известных предков до наших дней, строго по фактам.
// Не JSON-режим — здесь нужен настоящий текст, а не структура. Модель
// получает ПОЛНЫЙ список людей и связей (для среднего семейного дерева
// это укладывается в разумный контекст) и явную инструкцию писать так,
// чтобы из текста было понятно, кто кому кем приходится — этим же
// текстом мы пользуемся дальше для всплывающих карточек над именами.
async function generateChronicle(personsLines, relationshipsLines, marinaName) {
  const prompt = `Напиши летопись рода — длинный связный рассказ по-русски, от самых дальних известных предков до наших дней, заканчивая ${marinaName}.
${HONESTY_RULES}
Дополнительные правила именно для летописи:
- Никакого художественного вымысла, домыслов о характерах, чувствах или несуществующих событиях — только то, что есть в данных ниже.
- Каждый раз, когда впервые упоминаешь человека, называй его ПОЛНЫМ именем (фамилия, имя, отчество) ровно в том виде, как оно дано ниже — это важно для технической обработки текста, не сокращай и не склоняй мимо падежа именительного при первом упоминании.
- Явно проговаривай, кто кому кем приходится (сын, дочь, жена, брат и т.д.), чтобы по тексту можно было понять родственные связи, не только даты.
- Structура: раздели на главы по поколениям или ветвям (используй заголовки вида "## Название главы").
- Если про человека почти ничего не известно, кроме имени и связи — так и напиши коротко, не выдумывай подробности для баланса.
- Это черновик, который будет пополняться по мере того, как в дереве появляются новые люди — не пиши "это неполная версия" или подобные оговорки, просто расскажи то, что известно сейчас.

Все известные люди:
${personsLines}

Все известные связи:
${relationshipsLines}

Пиши подробно и связно — это не список, а текст-летопись, ориентируйся на объём около 1500-2500 слов, если данных достаточно.`;

  return callDeepSeek([{ role: "user", content: prompt }], { jsonMode: false, temperature: 0.3, maxTokens: 8000 });
}

