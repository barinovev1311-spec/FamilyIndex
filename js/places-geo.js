// places-geo.js — настоящие координаты мест рода. В отличие от старой
// декоративной SVG-схемы, здесь честно: где координата точная (город,
// существующий посёлок) — так и указано; где деревня исчезла и точное
// место утрachено — координата приблизительная, и это явно подписано.
// Ничего не выдумано: Кострома и Вохма — по открытым источникам
// (Википедия), Согра — вычислена по известному "13 км к северо-западу
// от Вохмы" оттуда же. Ершово и Мартьяновцы — того же Хорошевского
// сельсовета, что и Вохма, но точных координат исчезнувших деревень
// в открытых источниках нет — стоят рядом с Вохмой с пометкой
// "приблизительно".

window.PLACE_COORDS = {
  "г. Кострома": { lat: 57.7665, lng: 40.9269, precise: true },
  "Город Кострома": { lat: 57.7665, lng: 40.9269, precise: true },
  "Кострома, Трудовая слобода": { lat: 57.7719, lng: 40.9147, precise: true },
  "Вохомский район, д. Ершово": { lat: 58.965, lng: 46.71, precise: false },
  "Мартьяновцы": { lat: 58.958, lng: 46.735, precise: false },
  "с. Согра": { lat: 59.0095, lng: 46.59, precise: true },
  // Филино — место рождения самой Марины, в данных указана только
  // область без района; точных координат этой конкретной деревни найти
  // не удалось (в Костромской области несколько деревень с этим
  // названием) — честно помечаем как неустановленное, а не гадаем
  "Костромская обл, д. Филино": { lat: null, lng: null, precise: false, unresolved: true },
};

// пытается найти координаты по строке места, допуская небольшие
// расхождения в написании (используется и точное совпадение, и
// вхождение подстроки в обе стороны)
window.resolvePlaceCoords = function (placeName) {
  if (!placeName) return null;
  if (window.PLACE_COORDS[placeName]) return window.PLACE_COORDS[placeName];
  const keys = Object.keys(window.PLACE_COORDS);
  const found = keys.find((k) => k.includes(placeName) || placeName.includes(k));
  return found ? window.PLACE_COORDS[found] : null;
};
