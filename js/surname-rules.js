// surname-rules.js — автоматический (правило-ориентированный) черновик
// происхождения фамилии, когда в базе (window.SURNAME_ORIGINS) для неё
// ещё нет проверенной статьи.
//
// Это НЕ вызов ИИ и не факт — набор типовых правил русской ономастики
// (окончание -ов/-ин/-ский и т.д.). Результат всегда явно помечается
// как «автоматическая версия, не проверено», ровно как поисковые
// системы генеалогии в приложении отделяют факт от гипотезы.

function stripGenderSuffix(name) {
  // приводим женскую форму к мужской основе, где это типовой случай
  const rules = [
    [/ская$/i, "ский"], [/цкая$/i, "цкий"],
    [/ова$/i, "ов"], [/ева$/i, "ев"], [/ёва$/i, "ёв"],
    [/ина$/i, "ин"], [/ына$/i, "ын"],
  ];
  for (const [re, rep] of rules) if (re.test(name)) return name.replace(re, rep);
  return name;
}
export { stripGenderSuffix };

const OCCUPATIONAL_ROOTS = [
  ["кузнец", "от «кузнец» — фамилия по ремеслу предка"],
  ["гончар", "от «гончар» — фамилия по ремеслу предка"],
  ["мельник", "от «мельник» — фамилия по роду занятий"],
  ["плотник", "от «плотник» — фамилия по ремеслу"],
  ["ткач", "от «ткач» — фамилия по ремеслу"],
  ["сапожник", "от «сапожник» — фамилия по ремеслу"],
  ["рыбак", "от «рыбак» — фамилия по промыслу"],
  ["охотник", "от «охотник» — фамилия по промыслу"],
  ["купец", "от «купец» — фамилия по роду занятий предка"],
  ["поп", "вероятно, из семьи духовного сословия"],
  ["дьяк", "вероятно, из семьи духовного сословия"],
];

export function guessSurnameOrigin(lastNameRaw) {
  const lastName = (lastNameRaw || "").trim();
  if (!lastName) return null;
  const base = stripGenderSuffix(lastName).toLowerCase();

  for (const [root, text] of OCCUPATIONAL_ROOTS) {
    if (base.includes(root)) return { origin: text, uncertain: true };
  }

  if (/ых$|их$/i.test(lastName)) {
    return {
      origin: "Фамилия во множественном числе на «-ых/-их» — характерная форма патронима для говоров Русского Севера и Приуралья («дети такого-то», «...ские люди»), а не ошибка склонения.",
      uncertain: true,
    };
  }
  if (/ский$|цкий$/i.test(base)) {
    return {
      origin: "Фамилия на «-ский» — чаще всего происходит либо от географического названия (топонима), либо была присвоена при обучении в духовном училище в XVIII–XIX веках взамен простой деревенской фамилии.",
      uncertain: true,
    };
  }
  if (/ин$|ын$/i.test(base)) {
    return {
      origin: "Фамилия на «-ин» — типичная модель для фамилий, образованных от прозвища или имени, оканчивающегося на «-а»/«-я» (например, «Скряба» → «Скрябин»).",
      uncertain: true,
    };
  }
  if (/ов$|ев$|ёв$/i.test(base)) {
    return {
      origin: "Фамилия на «-ов/-ев» — самая распространённая модель русских фамилий, образованная от имени или прозвища отца («сын такого-то»).",
      uncertain: true,
    };
  }
  if (/енко$|ко$/i.test(lastName)) {
    return {
      origin: "Окончание «-енко/-ко» — украинского происхождения, часто означает «сын такого-то» или указывает на выходца с Украины.",
      uncertain: true,
    };
  }
  return {
    origin: "Устойчивой типовой модели окончания не обнаружено — похоже на редкую или локальную фамилию. Стоит уточнить у старших родственников или поискать в местных краеведческих источниках.",
    uncertain: true,
  };
}

// определяет "линию" для карточки происхождения по уже вычисленному
// родству человека к Марине (см. relations.js) — переиспользуем расчёт,
// а не гадаем заново
export function sideLabelForOrigin(side) {
  if (side === "father") return "линия отца";
  if (side === "mother") return "линия матери";
  if (side === "husband") return "родня со стороны мужа";
  return "родство уточняется";
}
